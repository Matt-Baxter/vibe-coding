"""Build movies-data.js for movie-picker.html from IMDb's free datasets.

Usage:
    python3 build_data.py [DOWNLOAD_DIR]

Downloads title.basics.tsv.gz and title.ratings.tsv.gz from
https://datasets.imdbws.com/ into DOWNLOAD_DIR (default: a temp folder,
about 240 MB) unless they are already there, then writes a trimmed
movies-data.js next to this script.

IMDb data is for personal, non-commercial use:
https://developer.imdb.com/non-commercial-datasets/
"""

import gzip
import json
import os
import sys
import tempfile
import urllib.request
from datetime import date

BASE_URL = "https://datasets.imdbws.com/"
FILES = ["title.basics.tsv.gz", "title.ratings.tsv.gz"]
MIN_VOTES = 5000  # floor kept in the data file; the app filters upward from here
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "movies-data.js")


def download(folder):
    os.makedirs(folder, exist_ok=True)
    for name in FILES:
        path = os.path.join(folder, name)
        if os.path.exists(path):
            print(f"using existing {path}")
            continue
        print(f"downloading {BASE_URL + name} ...")
        urllib.request.urlretrieve(BASE_URL + name, path)


def rows(path):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        next(f)  # header
        for line in f:
            yield line.rstrip("\n").split("\t")


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else os.path.join(tempfile.gettempdir(), "imdb")
    download(folder)

    ratings = {}
    for tconst, avg, votes in rows(os.path.join(folder, "title.ratings.tsv.gz")):
        if int(votes) >= MIN_VOTES:
            ratings[tconst] = (float(avg), int(votes))

    genres = []
    genre_index = {}
    movies = []
    for p in rows(os.path.join(folder, "title.basics.tsv.gz")):
        tconst, ttype, title, _orig, adult, year, _end, runtime, genre_str = p
        if ttype != "movie" or adult == "1" or tconst not in ratings or year == r"\N":
            continue
        rating, votes = ratings[tconst]
        mask = 0
        if genre_str != r"\N":
            for g in genre_str.split(","):
                if g not in genre_index:
                    genre_index[g] = len(genres)
                    genres.append(g)
                mask |= 1 << genre_index[g]
        movies.append([
            title,
            int(year),
            int(runtime) if runtime != r"\N" else 0,  # 0 = unknown
            mask,
            rating,
            votes,
            int(tconst[2:]),
        ])

    # Re-number genres alphabetically so the app's dropdown is sorted.
    order = sorted(range(len(genres)), key=lambda i: genres[i])
    remap = {old: new for new, old in enumerate(order)}
    for m in movies:
        old, new = m[3], 0
        for i in range(len(genres)):
            if old & (1 << i):
                new |= 1 << remap[i]
        m[3] = new
    genres = [genres[i] for i in order]
    movies.sort(key=lambda m: (-m[4], -m[5]))

    data = {
        "built": date.today().isoformat(),
        "minVotes": MIN_VOTES,
        "genres": genres,
        "fields": ["title", "year", "runtime", "genreMask", "rating", "votes", "imdbId"],
        "movies": movies,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build_data.py from IMDb datasets. Do not edit by hand.\n")
        f.write("// Information courtesy of IMDb (https://www.imdb.com). Used with permission.\n")
        f.write("window.MOVIE_DATA = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {len(movies)} movies, {len(genres)} genres to {OUT} "
          f"({os.path.getsize(OUT) / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
